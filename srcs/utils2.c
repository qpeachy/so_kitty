#include "so_long.h"

int	num_size(int n)
{
	int	cnt;

	cnt = 0;
	if (n < 10)
		return (1);
	{
		while (n != 0)
		{
			cnt++;
			n /= 10;
		}
	}
	return (cnt);
}
